namespace Stathub.Modules.Matches.Domain.Enums;

/// <summary>
/// Тип события протокола матча.
/// Отмена события — отдельный универсальный тип <see cref="EventVoided"/> со ссылкой
/// на отменяемое событие, а не отдельные типы «отменённый гол» / «отменённая карточка»
/// (см. AGENTS.md, «Особенности домена»).
/// </summary>
public enum MatchEventType
{
    Goal = 0, // Гол
    OwnGoal = 1, // Автогол
    YellowCard = 2, // Жёлтая карточка
    RedCard = 3, // Красная карточка
    Substitution = 4, // Замена
    EventVoided = 5, // Отмена другого события протокола

    // Жизненный цикл: судья ведёт матч офлайн, поэтому смена статуса идёт той же очередью,
    // что и голы, и порядок «последний гол → финальный свисток» не может нарушиться.
    MatchStarted = 6, // Начало матча
    MatchPaused = 7, // Остановка игры
    MatchResumed = 8, // Продолжение игры
    PeriodStarted = 9, // Начало следующего периода
    MatchFinished = 10, // Финальный свисток

    // Командная статистика: отмечает статистик, на счёт и статус матча не влияет.
    // Удар в створ — тоже удар: в итоговом «Удары» учитываются оба типа.
    Shot = 11, // Удар мимо створа
    ShotOnTarget = 12, // Удар в створ
    Foul = 13, // Фол
    Corner = 14 // Угловой
}
