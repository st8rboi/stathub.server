namespace Stathub.Modules.Matches.Domain.Enums;

/// <summary>
/// Вид гола (<see cref="MatchEventType.Goal"/>). Это уточнение гола, а не отдельный тип события:
/// счёт, отмена и статистика работают с голом одинаково, меняется только вес и подпись.
/// У событий, принятых до появления видов, значения нет — это обычный гол.
/// Автогол остаётся отдельным типом события: он засчитывается сопернику.
/// </summary>
public enum GoalKind
{
    Regular = 0, // Гол с игры
    Penalty = 1, // Гол с пенальти: без ассистента
    Bonus = 2 // Бонусный мяч: идёт в счёт за два, автору и ассистенту тоже по два
}
